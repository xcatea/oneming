export const CN_PROVINCES = CN_RAW.map(([name, tz, list]) => ({
  name,
  tz,
  cities: list.split(",").map((s) => { const i = s.lastIndexOf(":"); return { name: s.slice(0, i), lon: Number(s.slice(i + 1)) } }),
}))

export const WORLD_REGIONS = WORLD_RAW.map(([zh, en, cities]) => ({
  zh, en, cities: cities.map(([czh, cen, lon, tz]) => ({ zh: czh, en: cen, lon, tz })),
}))

// 地点 ID：中国 "cn:省:市"，海外 "w:英文名"
const INDEX = new Map()
for (const p of CN_PROVINCES) for (const c of p.cities) {
  INDEX.set(`cn:${p.name}:${c.name}`, { id: `cn:${p.name}:${c.name}`, zh: `${p.name.replace(/(特别行政区|维吾尔自治区|壮族自治区|回族自治区|自治区|省|市)$/, "")} ${c.name}`, en: c.name, lon: c.lon, tz: p.tz, cn: !p.tz })
}
for (const r of WORLD_REGIONS) for (const c of r.cities) {
  INDEX.set(`w:${c.en}`, { id: `w:${c.en}`, zh: c.zh, en: c.en, lon: c.lon, tz: c.tz, cn: false })
}
export function placeById(id) { return (id && INDEX.get(id)) || null }
